  readonly availableLocales: Array<{ value: AppLocale; label: string; nativeLabel: string }> = [
    { value: 'zh', label: 'Chinese', nativeLabel: '中文' },
    { value: 'en', label: 'English', nativeLabel: 'English' }
  ];

  constructor() {
    effect(() => {
      const locale = this.locale();
      if (typeof document !== 'undefined') {
        document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
      }
      if (this.canUseLocalStorage()) {
        localStorage.setItem(LOCALE_STORAGE_KEY, locale);
      }
    });
  }

  setLocale(locale: AppLocale) {
    this.locale.set(locale);
  }

  toggleLocale() {
    this.setLocale(this.locale() === 'en' ? 'zh' : 'en');
  }

  isEnglish(): boolean {
    return this.locale() === 'en';
  }

  translate(value: string | null | undefined): string {
    if (value == null || this.locale() === 'zh') return value ?? '';
    return this.translateToEnglish(value);
  }

  translateData(value: string | null | undefined, englishFallback?: string): string {
    if (value == null) return '';
    if (this.locale() === 'zh') return value;

    const translated = this.translateToEnglish(value);
    if (!this.hasCjk(translated)) return translated;

    return englishFallback ?? this.compactEnglishFallback(value);
  }

  translateList(values: string[] | null | undefined): string[] {
    if (!values?.length) return [];
    return values.map(value => this.translateData(value));
  }

  hasCjk(value: string | null | undefined): boolean {
    return /[\u3400-\u9fff]/u.test(value ?? '');
  }

  translateToEnglish(value: string): string {
    if (!value.trim()) return value;

    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    const core = value.trim().replace(/\s+/g, ' ');
    const translated = this.translateCore(core);

    return `${leading}${translated}${trailing}`;
  }

  private translateCore(core: string): string {
    const exact = EXACT_TRANSLATIONS[core];
    if (exact) return exact;

    const dynamic = this.translateDynamic(core);
    if (dynamic) return dynamic;

    const mixed = this.translateMixedCore(core);
    if (mixed) return mixed;

    return core;
  }

  private translateMixedCore(core: string): string | null {
    const replaced = core
      .replaceAll('协议', 'License')
      .replaceAll('作者：', 'Author: ')
      .replaceAll('主编：', 'Editor-in-Chief: ')
      .replaceAll('出版社', ' Press');

    return replaced !== core ? replaced : null;
  }

  private compactEnglishFallback(value: string): string {
    const normalized = value
      .replace(/[《》“”‘’]/g, '')
      .replace(/[，。；：、]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();

    if (!normalized) return '';
    if (!this.hasCjk(normalized)) return normalized;

    const loose = this.translateLooseChineseTerms(normalized);
    if (loose && !this.hasCjk(loose)) return loose;

    if (/二维码|微信|咨询/.test(normalized)) return 'Consultation QR code';
    if (/示意图|主图|封面/.test(normalized)) return 'Reference image';
    if (/详情图/.test(normalized)) return 'Detail image';
    if (/缩略图/.test(normalized)) return 'Thumbnail image';
    if (/规范|条文|标准/.test(normalized)) return 'Standards reference';
    if (/资源|服务/.test(normalized)) return 'Resource item';

    return 'Reference item';
  }

